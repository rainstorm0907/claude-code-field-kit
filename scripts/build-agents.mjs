#!/usr/bin/env node
// Generate Claude Code agent definitions from the agent-taskforce contracts in skills/.
// Usage: node scripts/build-agents.mjs [--check]
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const body = (text) => text.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '').trim();
const read = async (rel) => body(await readFile(path.join(root, 'skills', rel), 'utf8'));

const receiving = await read('dispatched/SKILL.md');
const teammate = await read('agent-taskforce/TEAMMATE.md');
const runtime = `# Claude Code runtime

Your role is assigned; inherited lead conversation does not make you the lead. The brief and authoritative artifacts define your task. Do not invent a mission or frame when none is needed. The receiving contract is included below.

The installed agent-taskforce skill's \`runtimes/claude-code.md\` maps the actual tools (SendMessage, the shared task list, subagents); resolve its links from that skill directory. Read the dispatching skill before delegating. Preserve the approved team roster.

Roles are not pinned to a model. For new subagents, choose a model through the model-guide skill and the user's constraints. A subagent is a session that remembers: send the next related slice to the same agent, and start a new one only for a different problem, a cold review, or one stuck on a wrong idea.`;

const roles = [
  ['workstream-owner', 'Agent-team owner: holds one bounded outcome through investigation, authorized implementation, local verification and handoff.',
    [teammate, await read('agent-taskforce/teammate/workstream-owner.md')]],
  ['independent-verifier', 'Agent-team verifier: independently checks artifacts and acceptance evidence in a fresh context; sends defects straight to the owner.',
    [teammate, await read('agent-taskforce/teammate/independent-verifier.md')]],
];

await mkdir(path.join(root, 'agents'), { recursive: true });
for (const [name, description, parts] of roles) {
  const instructions = [runtime, ...parts, receiving].join('\n\n');
  // Model is left out so the lead picks it per task.
  const content = `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n\n<!-- Generated by scripts/build-agents.mjs from skills/. Edit the skill sources instead. -->\n\n${instructions}\n`;
  const dest = path.join(root, 'agents', `${name}.md`);
  if (check) {
    if ((await readFile(dest, 'utf8')) !== content) throw new Error(`Stale generated agent: ${name}`);
  } else {
    await writeFile(dest, content);
  }
  console.log(`${name}: ${check ? 'current' : 'generated'}`);
}
